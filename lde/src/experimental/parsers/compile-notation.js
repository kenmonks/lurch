///////////////////////////////////////////////////////////////////////////
// Regenerate lurch-notation-compiled.js from lurch-notation.txt
//
// The
// notation file is plain text, but the parser's import chain must stay
// synchronous and browser-compatible, so a small GENERATED ES-module
// wrapper embeds the file's text and content hash.  The
// wrapper is pure data: notation-tables.js compiles the embedded text
// through notation-loader.js at import time (well under a millisecond)
// and the result IS the live notation tables.  Lode's .compilenotation
// command runs this script, the .compileparser analog; the golden suite
// (notation-parity.js) recomputes the hash of the .txt on disk and fails
// loudly when the wrapper is stale.
//
// Usage:  node compile-notation.js     (from the parsers folder, or via
//                                       Lode's .compilenotation)

import fs from 'fs'
import path from 'path'
import { createHash } from 'crypto'
import { fileURLToPath } from 'url'
import { loadNotation } from './notation-loader.js'
import { precedence } from './notation-tables.js'
import { lintFreshCompile } from './notation-parity.js'

const here = path.dirname(fileURLToPath(import.meta.url))
const srcPath = path.join(here, 'lurch-notation.txt')
const outPath = path.join(here, 'lurch-notation-compiled.js')

const text = fs.readFileSync(srcPath, 'utf8')
export const hashOf = s => createHash('sha256').update(s).digest('hex')
const hash = hashOf(text)

// refuse to embed a file that does not load cleanly
const { tables, lineOf, errors } = loadNotation(text, precedence)
if ( errors.length ) {
  console.error(`lurch-notation.txt does not compile; wrapper NOT written:`)
  errors.forEach( e => console.error(`  ${e}`) )
  process.exit(1)
}

// ... or that would fail the parser's load-time structural lint ("if it
// compiles, it works when loaded"); warnings are
// printed but do not block, matching the load-time behavior
const lint = lintFreshCompile(tables, lineOf)
if ( lint.errors.length ) {
  console.error(`lurch-notation.txt does not lint; wrapper NOT written:`)
  lint.errors.forEach( e => console.error(`  ${e}`) )
  process.exit(1)
}
lint.warnings.forEach( w => console.warn(`  ⚠ ${w}`) )

const wrapper = `///////////////////////////////////////////////////////////////////////////
// GENERATED by compile-notation.js (Lode: .compilenotation) - DO NOT EDIT
//
// This wrapper embeds lurch-notation.txt so the parser's static import
// chain stays synchronous and browser-compatible.  It is
// pure data: notation-tables.js compiles this embedded text through
// notation-loader.js at import time, and the result IS the live notation
// tables.  The golden suite fails loudly when the embedded copy is stale
// (notation-parity.js compares notationFileHash to the hash of the .txt
// on disk).  Edit lurch-notation.txt and rerun .compilenotation.

// sha256 of the embedded source text
export const notationFileHash = ${JSON.stringify(hash)}

export const notationFileText =
  ${JSON.stringify(text)}
`

fs.writeFileSync(outPath, wrapper)
console.log(`Wrote ${outPath}`)
console.log(`  source: lurch-notation.txt (sha256 ${hash.slice(0, 12)}…,` +
            ` ${text.length} chars)`)
